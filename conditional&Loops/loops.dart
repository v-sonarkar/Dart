void main(){


  // For loop
  for (int i = 0; i < 5; i++) {
    print("For loop iteration: $i");
  }

  // While loop
  int j = 0;
  while (j < 5) {
    print("While loop iteration: $j");
    j++;
  }

  // Do-while loop
  int k = 0;
  do {
    print("Do-while loop iteration: $k");
    k++;
  } while (k < 5);
}